// Splits the imported blog archive so the browser only downloads what a page needs.
//
// importedPosts.generated.json holds every post in full (~3.9 MB), and every page
// on the site was shipping all of it in the main bundle. Body text and FAQs are
// ~95% of that and are only needed on the post being read, so they are written out
// one file per post (loaded on demand by src/lib/posts.js), while everything the
// listings, breadcrumbs, canonical tags and route tables need stays in one small
// metadata file. The source JSON is untouched and stays the single source of truth;
// both outputs are build products (gitignored) regenerated by dev/build.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/data/posts')
const posts = JSON.parse(readFileSync(join(root, 'src/data/importedPosts.generated.json'), 'utf8'))

rmSync(out, { recursive: true, force: true })
mkdirSync(join(out, 'bodies'), { recursive: true })

const meta = posts.map(({ body, faqs, ...rest }) => {
  writeFileSync(join(out, 'bodies', `${rest.slug}.json`), JSON.stringify({ body, faqs: faqs ?? [] }))
  return rest
})
writeFileSync(join(out, 'meta.generated.json'), JSON.stringify(meta))
console.log(`post bodies: ${posts.length} split into src/data/posts/`)
