// Builds the dot-matrix world maps used by the SMS Broadcasting hero and the country-codes hero ahead of time.
//
// `dotted-map` carries the whole land mask (about 150 KB gzipped) and was being
// shipped to every visitor on every page just to draw two pictures on two pages. The
// results never change, so it is generated here instead: each map as a static SVG in
// public/, and the pixel position of each pin in a small JSON the component reads.
// Pins and styling must stay in step with src/components/SmsBroadcastHero.jsx and
// src/pages/country/HeroStage.jsx.
// Both outputs are build products (gitignored) regenerated by dev/build.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import DottedMap from 'dotted-map'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

mkdirSync(join(root, 'public'), { recursive: true })

function build({ name, height, pins, svgOptions, pinStyle }) {
  const map = new DottedMap({ height, grid: 'diagonal' })
  for (const p of pins) map.addPin({ lat: p.lat, lng: p.lng, svgOptions: pinStyle, data: { code: p.code } })
  const svg = map.getSVG({ radius: 0.22, shape: 'circle', backgroundColor: 'transparent', ...svgOptions })
  const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)
  const points = {}
  for (const pt of map.getPoints()) if (pt.data?.code) points[pt.data.code] = { x: pt.x, y: pt.y }
  writeFileSync(join(root, `public/${name}.svg`), svg)
  writeFileSync(
    join(root, `src/data/${name}.generated.json`),
    JSON.stringify({ width: parseFloat(vb[1]), height: parseFloat(vb[2]), points }),
  )
  console.log(`${name}: ${Math.round(svg.length / 1024)} KB svg, ${pins.length} pins`)
}

